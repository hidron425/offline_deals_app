// lib/category_labels.dart
//
// Отображаемые названия категорий магазинов.
//
// В БД (shops.category) ключи остаются английскими: на них завязана логика
// ежедневных ограничений — «одно кафе в день», «одна электроника в день»
// (_lastCafeDate / _lastElectronicsDate), условия баннеров и ежедневные
// задания. Переводим только то, что видит пользователь.
//
// Файл общий для вкладки «Карта», карточки магазина и экрана квеста, чтобы
// переводы не разъехались по копиям.

/// Ключ -> подпись. Ключи — ровно те значения, что лежат в shops.category.
const Map<String, String> categoryLabels = {
  'cafe': 'Кафе',
  'clothing': 'Одежда и обувь',
  'electronics': 'Электроника',
  'other': 'Разное',
};

/// Подпись категории для UI. Неизвестный ключ показываем как есть: лучше
/// английское слово, чем пустое место, и сразу видно, что нужен перевод.
String categoryLabel(String category) =>
    categoryLabels[category] ?? category;
