// Русские формы слов для подписей в UI. Общий файл, чтобы одна и та же
// формулировка не разъезжалась по экранам: «через 1 цикл», «через 2 цикла»,
// «через 5 циклов».

/// Форма слова «цикл» для числа [n].
///
/// Правило стандартное: 11-14 — «циклов» (исключение), далее по последней
/// цифре: 1 — «цикл», 2-4 — «цикла», остальное — «циклов».
String cyclePlural(int n) {
  final abs = n.abs();
  final mod100 = abs % 100;
  if (mod100 >= 11 && mod100 <= 14) return 'циклов';
  final mod10 = abs % 10;
  if (mod10 == 1) return 'цикл';
  if (mod10 >= 2 && mod10 <= 4) return 'цикла';
  return 'циклов';
}
